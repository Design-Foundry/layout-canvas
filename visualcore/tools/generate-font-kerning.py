"""Regenerate trusted Inter face Latin pair advances (development only; requires fontTools).

stb_truetype does not resolve GPOS extension lookup 9. Extract the trusted font's
default `kern` feature, including extension PairPos format 1/2. Font bytes stay
unmodified. Nonzero placement/second-glyph adjustments are deliberately refused.
"""
from pathlib import Path
import hashlib
import sys
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
faces = {
    'regular': ('Inter', 'cf3cb43b0366e2dc6df60e1132b1c9a4c15777f0cd8e5a53e0c15124003e9ed4'),
    'bold': ('CanvasInter-Bold', 'e08273de48feb18e9211f04eddd8e2c76ae9406f2befd71abfd7b01fc7a8d92c'),
    'oblique': ('CanvasInter-Oblique', '7a05f8ae4e714907434f5c70aced7aeaebfedb1f4f2b5eef42587b40db602f3d'),
    'bold_oblique': ('CanvasInter-BoldOblique', '5361476462b7af7bb5bdf351143efe00192c7a7556a0e17d2ab34231a9d437f5'),
}
assert len(sys.argv) <= 2
style = sys.argv[1] if len(sys.argv) == 2 else 'regular'
filename, expected = faces[style]
source = ROOT / f'assets/fonts/{filename}.ttf'
bold = style == 'bold'
assert hashlib.sha256(source.read_bytes()).hexdigest() == expected
font = TTFont(source)
gpos = font['GPOS'].table
lookups = sorted({i for record in gpos.FeatureList.FeatureRecord if record.FeatureTag == 'kern' for i in record.Feature.LookupListIndex})
cmap = font.getBestCmap()
characters = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100)) + [0x2013,0x2014,0x2018,0x2019,0x201a,0x201c,0x201d,0x201e,0x2022,0x2026,0x2039,0x203a,0x20ac,0x2122]

def advance(table, first, second):
    if first not in table.Coverage.glyphs:
        return None
    if table.Format == 1:
        pair = next((p for p in table.PairSet[table.Coverage.glyphs.index(first)].PairValueRecord if p.SecondGlyph == second), None)
        if pair is None:
            return None
    elif table.Format == 2:
        pair = table.Class1Record[table.ClassDef1.classDefs.get(first, 0)].Class2Record[table.ClassDef2.classDefs.get(second, 0)]
    else:
        raise ValueError('Unsupported pair format')
    one, two = pair.Value1, pair.Value2
    assert not any(getattr(one, key, 0) for key in ['XPlacement','YPlacement','YAdvance'])
    assert not any(getattr(two, key, 0) for key in ['XPlacement','YPlacement','XAdvance','YAdvance'])
    return getattr(one, 'XAdvance', 0)

pairs = []
for a in sorted(characters):
    for b in sorted(characters):
        total = 0
        for index in lookups:
            lookup = gpos.LookupList.Lookup[index]
            for sub in lookup.SubTable:
                kind = sub.ExtensionLookupType if lookup.LookupType == 9 else lookup.LookupType
                assert kind == 2
                value = advance(sub.ExtSubTable if lookup.LookupType == 9 else sub, cmap[a], cmap[b])
                if value is not None:
                    total += value
                    break
        if total:
            pairs.append(f'    {{{(a << 16) | b}u, {total}}},')
target = ROOT / ('src/inter_kerning.inc' if style == 'regular' else f'src/inter_{style}_kerning.inc')
description = 'the static OFL Inter 700/upright derivative' if bold else 'the unmodified OFL Inter font' if style == 'regular' else f'the static OFL Inter {style} derivative'
target.write_text('// Generated by tools/generate-font-kerning.py from ' + description + '.\n' + '\n'.join(pairs) + '\n',encoding='utf-8')
print(len(pairs),'nonzero default pair advances;',font['head'].unitsPerEm,'units/em')
